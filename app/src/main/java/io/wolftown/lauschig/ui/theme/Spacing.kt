package io.wolftown.lauschig.ui.theme

import androidx.compose.ui.unit.dp

/** The app's spacing steps, so pages share one rhythm. */
object Spacing {
    val xs = 4.dp
    val s = 8.dp
    val m = 12.dp
    val l = 16.dp
    val xl = 24.dp

    /** Side padding of a page. */
    val gutter = l

    /** Between tiles in a row or a grid. */
    val tileGap = m

    /** Above a section's header, between two sections of a page. */
    val section = l
}
